"""Phase 6 editorial: load drafts and reviewed entries, approve, write the review document.

    python -m pipeline.editorial approve <cluster|resort> <id> [--by NAME]
    python -m pipeline.editorial approve-all --by NAME [--date YYYY-MM-DD]

Only reviewed entries reach data/build. docs/map/editorial-review.md lists every
draft for Alexandre (regenerated by each build).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

import yaml
from pydantic import ValidationError

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    __package__ = "pipeline"

from pipeline.schemas.editorial import EditorialBatch, EditorialEntry  # noqa: E402
from pipeline.sources import SourceRegistry  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent


@dataclass
class LoadedEntry:
    path: Path
    entry: EditorialEntry
    warnings: list[str] = field(default_factory=list)


@dataclass
class EditorialData:
    entries: list[LoadedEntry] = field(default_factory=list)

    def reviewed(self, target: str) -> dict[str, EditorialEntry]:
        return {e.entry.id: e.entry for e in self.entries if e.entry.target == target and e.entry.status == "reviewed"}

    @property
    def drafts(self) -> list[LoadedEntry]:
        return [e for e in self.entries if e.entry.status == "draft"]


def load_editorial(raw_dir: Path, registry: SourceRegistry, resort_ids: set[str], cluster_ids: set[str], rel=str
                   ) -> tuple[EditorialData, list[str]]:
    """Validate data/raw/editorial/*.yaml. Returns (data, errors)."""
    from pipeline.tier_a import _register_sources, _yaml_files

    errors: list[str] = []
    files = _yaml_files(raw_dir / "editorial")
    raws: dict[Path, Any] = {}
    for p in files:
        try:
            raws[p] = yaml.safe_load(p.read_text(encoding="utf-8"))
        except yaml.YAMLError as e:
            errors.append(f"{rel(p)}: YAML parse error: {e}")
            continue
        _register_sources(raws[p], rel(p), registry, errors)
    data = EditorialData()
    seen: dict[tuple[str, str], str] = {}
    for p in files:
        if not isinstance(raws.get(p), dict):
            continue
        try:
            batch = EditorialBatch.model_validate(raws[p], context=registry.context())
        except ValidationError as e:
            for m in e.errors():
                loc = list(m["loc"])
                where = rel(p)
                if len(loc) >= 2 and loc[0] == "entries" and isinstance(loc[1], int):
                    try:
                        raw = raws[p]["entries"][loc[1]]
                        where = f"{rel(p)} {raw.get('target')} '{raw.get('id')}'"
                    except (KeyError, IndexError, AttributeError, TypeError):
                        pass
                    loc = loc[2:]
                errors.append(f"{where}: {'.'.join(map(str, loc)) or '(entry)'}: {m['msg']}")
            continue
        for e in batch.entries:
            key = (e.target, e.id)
            known = resort_ids if e.target == "resort" else cluster_ids
            if e.id not in known:
                errors.append(f"{rel(p)} {e.target} '{e.id}': no such {e.target} in this build")
            if key in seen:
                errors.append(f"{rel(p)} {e.target} '{e.id}': also defined in {seen[key]}")
            seen[key] = rel(p)
            data.entries.append(LoadedEntry(p, e, e.lint_warnings()))
    return data, errors


def resort_editorial(entry: Optional[EditorialEntry]) -> Optional[dict]:
    """Resort.editorial for a reviewed entry, else None."""
    if entry is None or entry.status != "reviewed":
        return None
    return {"overview_md": entry.overview_md, "culture_md": entry.culture_md,
            "alexandre_take_md": entry.alexandre_take_md, "status": "reviewed", "source_ids": list(entry.source_ids),
            "reviewed_date": entry.reviewed_date.isoformat() if entry.reviewed_date else None}


# -------------------------------------------------------------------- approve
_ITEM = re.compile(r"^(\s*)-\s")


def approve_in_file(path: Path, target: str, entry_id: str, by: str, date: dt.date) -> bool:
    """Flip one entry to reviewed in place, keeping the rest of the file (comments, order) untouched."""
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    start = next((i for i, l in enumerate(lines) if re.match(r"^entries:\s*$", l)), None)
    if start is None:
        return False
    # the entries section ends at the next top level key
    end = next((i for i in range(start + 1, len(lines))
                if lines[i].strip() and not lines[i].startswith((" ", "\t", "-", "#"))), len(lines))
    first = next((i for i in range(start + 1, end) if _ITEM.match(lines[i])), None)
    if first is None:
        return False
    indent = len(_ITEM.match(lines[first]).group(1))
    items = [i for i in range(start + 1, end) if (m := _ITEM.match(lines[i])) and len(m.group(1)) == indent]
    for n, i0 in enumerate(items):
        i1 = items[n + 1] if n + 1 < len(items) else end
        block = "".join(lines[i0:i1])
        try:
            parsed = yaml.safe_load(block)
        except yaml.YAMLError:
            continue
        item = parsed[0] if isinstance(parsed, list) and parsed else None
        if not isinstance(item, dict) or item.get("target") != target or item.get("id") != entry_id:
            continue
        body = [j for j in range(i0, i1) if not lines[j].lstrip().startswith(("reviewed_by:", "reviewed_date:"))]
        status_j = next((j for j in body if re.match(r"^\s*(?:-\s+)?status:", lines[j])), None)
        if status_j is None:
            return False
        line = lines[status_j]
        col = line.index("status:")
        key_indent = " " * col if not line.lstrip().startswith("-") else " " * (len(line) - len(line.lstrip()) + 2)
        new_status = line[:col] + "status: reviewed\n"
        extra = [f"{key_indent}reviewed_by: {json.dumps(by)}\n", f"{key_indent}reviewed_date: {date.isoformat()}\n"]
        kept = [lines[j] if j != status_j else new_status for j in body]
        pos = kept.index(new_status) + 1
        kept[pos:pos] = extra
        new_text = "".join(lines[:i0] + kept + lines[i1:])
        check = yaml.safe_load(new_text)
        hit = [e for e in check.get("entries", []) if e.get("target") == target and e.get("id") == entry_id]
        if not hit or hit[0].get("status") != "reviewed":
            return False
        path.write_text(new_text, encoding="utf-8")
        return True
    return False


def approve(raw_dir: Path, target: str, entry_id: str, by: str, date: Optional[dt.date] = None) -> Path:
    """Approve the entry wherever it lives under data/raw/editorial. Raises LookupError when not found."""
    date = date or dt.date.today()
    for p in sorted((raw_dir / "editorial").glob("*.y*ml")):
        data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        if any(e.get("target") == target and e.get("id") == entry_id for e in data.get("entries") or []):
            if approve_in_file(p, target, entry_id, by, date):
                return p
            raise LookupError(f"found {target} '{entry_id}' in {p} but could not edit it; set status: reviewed by hand")
    raise LookupError(f"no editorial entry for {target} '{entry_id}' in {raw_dir / 'editorial'}")


def approve_all(raw_dir: Path, by: str, date: Optional[dt.date] = None) -> tuple[int, list[str]]:
    """Approve every draft under data/raw/editorial in place. Returns (approved, entries that could not be edited)."""
    date = date or dt.date.today()
    done, failed = 0, []
    for p in sorted((raw_dir / "editorial").glob("*.y*ml")):
        data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        for e in data.get("entries") or []:
            if e.get("status") == "draft":
                if approve_in_file(p, e.get("target"), e.get("id"), by, date):
                    done += 1
                else:
                    failed.append(f"{p.name}: {e.get('target')} '{e.get('id')}'")
    return done, failed


# --------------------------------------------------------------- review doc
def render_review(data: EditorialData, registry: SourceRegistry, tier_a_clusters: dict[str, str],
                  names: dict[tuple[str, str], str]) -> str:
    reviewed_clusters = data.reviewed("cluster")
    lines = [
        "# Editorial review",
        "",
        "Drafts waiting for Alexandre (ROADMAP Phase 6). Generated by `python pipeline/build.py` from "
        "`data/raw/editorial/`. Hand edits to this file are overwritten.",
        "",
        "**How to mark an entry reviewed:** set `status: reviewed` on the entry in its YAML file, or run "
        "`python -m pipeline.editorial approve <cluster|resort> <id> --by Alexandre`, which also records "
        "`reviewed_by` and `reviewed_date`. Only reviewed entries reach the map. Edit the text in the YAML first "
        "if it needs changes, and add your own notes in `alexandre_take_md`.",
        "",
        "## Phase 6 gate: Tier A clusters with a reviewed overview",
        "",
        "Named clusters with at least one Tier A resort. The per state fallback clusters (`other-<state>`) "
        "are state buckets and need no overview.",
        "",
    ]
    done = sorted(c for c in tier_a_clusters if c in reviewed_clusters)
    todo = sorted(c for c in tier_a_clusters if c not in reviewed_clusters)
    lines.append(f"{len(done)} of {len(tier_a_clusters)} Tier A clusters have a reviewed overview.")
    lines.append("")
    if todo:
        lines.append("Still needed: " + ", ".join(f"{tier_a_clusters[c]} (`{c}`)" for c in todo) + ".")
        lines.append("")
    drafts = sorted(data.drafts, key=lambda e: (e.entry.target, e.entry.id))
    reviewed_n = len(data.entries) - len(drafts)
    lines += [f"## Drafts ({len(drafts)}; {reviewed_n} reviewed)", ""]
    if not drafts:
        lines += ["No drafts are waiting.", ""]
    for le in drafts:
        e = le.entry
        title = names.get((e.target, e.id), e.id)
        lines += [f"### {e.target.capitalize()}: {title} (`{e.id}`)", "", f"File: `{le.path.name}`", ""]
        for fname, label in (("overview_md", "Overview"), ("culture_md", "Culture"), ("alexandre_take_md", "Alexandre's take")):
            text = getattr(e, fname)
            if text:
                lines += [f"**{label}**", ""] + [f"> {ln}" if ln else ">" for ln in text.strip().splitlines()] + [""]
        lines.append("**Sources:** " + ", ".join(
            f"[{registry.get(s).title}]({registry.get(s).url})" if s in registry else f"`{s}`" for s in e.source_ids))
        lines.append("")
        if le.warnings:
            lines += ["**Style warnings:**", ""] + [f"* {w}" for w in le.warnings] + [""]
        lines += [f"Approve: `python -m pipeline.editorial approve {e.target} {e.id} --by Alexandre`", ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Editorial review workflow.")
    sub = ap.add_subparsers(dest="command", required=True)
    a = sub.add_parser("approve", help="mark an entry reviewed")
    a.add_argument("target", choices=["cluster", "resort"])
    a.add_argument("id")
    a.add_argument("--by", default="Alexandre")
    a.add_argument("--date", type=dt.date.fromisoformat, default=None)
    b = sub.add_parser("approve-all", help="mark every draft reviewed")
    b.add_argument("--by", required=True)
    b.add_argument("--date", type=dt.date.fromisoformat, default=None)
    args = ap.parse_args(argv)
    if args.command == "approve-all":
        done, failed = approve_all(REPO_ROOT / "data" / "raw", args.by, args.date)
        for f in failed:
            print(f"could not edit {f}; set status: reviewed by hand", file=sys.stderr)
        print(f"approved {done} drafts; run python pipeline/build.py to publish them")
        return 1 if failed else 0
    try:
        path = approve(REPO_ROOT / "data" / "raw", args.target, args.id, args.by, args.date)
    except LookupError as e:
        print(str(e), file=sys.stderr)
        return 1
    print(f"approved {args.target} '{args.id}' in {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path}; "
          f"run python pipeline/build.py to publish it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
