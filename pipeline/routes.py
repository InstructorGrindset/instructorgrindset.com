def _badge(conf: Optional[str]) -> str:
    conf = conf or ""
    return f'<span class="badge badge-{_esc(conf)}">{_esc(CONFIDENCE_LABEL.get(conf, conf))}</span>'


def _host(url: str) -> str:
    m = re.match(r"^https://([^/:?#]+)", url)
    host = m.group(1).lower() if m else ""
    return host[4:] if host.startswith("www.") else host


def _link_meta(ctx: Ctx, item: dict) -> str:
    """'Last verified <date>' plus the source link when the source is another page than the link itself."""
    meta = f"Last verified {_esc(_date(item.get('as_of')))}"
    src = ctx.sources.get(item.get("source_id") or "") or {}
    if src.get("url") and src.get("url") != item.get("url"):
        link = _source_link(ctx, item.get("source_id"))
        meta += f" · {link}" if link else ""
    return meta


def render_webcams(ctx: Ctx, r: dict) -> str:
    """The "Live cams" row: "Open live cams" (the resort's cams page) and up to webcams.max_named_cams named cams."""
    w = r.get("webcams") or {}
    page = w.get("cams_page") or {}
    cams = [x for x in (w.get("cams") or []) if str(x.get("url", "")).startswith("https://")]
    parts = []
    if str(page.get("url", "")).startswith("https://"):
        parts.append(f'<p class="live-cams-main"><a class="live-cams-link" href="{_esc(page["url"])}" {NEW_TAB}>Open live cams</a> '
                     f'{_badge(page.get("confidence"))} <span class="fact-meta">{_esc(_host(page["url"]))} · opens in a new tab · '
                     f'{_link_meta(ctx, page)}</span></p>')
    if cams:
        lis = "".join(f'<li><a class="cam-link" href="{_esc(x["url"])}" {NEW_TAB}>{_esc(x["label"])}</a> {_badge(x.get("confidence"))} '
                      f'<span class="fact-meta">{_esc(WEBCAM_KIND.get(x.get("kind"), ""))}</span></li>' for x in cams)
        parts.append(f'<ul class="cam-list" aria-label="Named cams">{lis}</ul>')
    if not parts:
        return ""
    return f'<div class="live-cams"><p class="sub live-cams-title">Live cams</p>{"".join(parts)}</div>'


def render_jobs(ctx: Ctx, r: dict) -> str:
    """The "Jobs" section: links grouped as Ski school, Coaching and clubs, Management, Parent company, Job boards.
    Live postings are added by the panel from jobs/postings.json, never prerendered (they change daily)."""
    jobs = r.get("jobs") or {}
    links = [x for x in (jobs.get("links") or []) if str(x.get("url", "")).startswith("https://")]
    hw = jobs.get("hiring_window") or {}
    window = (f'<p class="jobs-window"><strong>Hiring window:</strong> {_esc(hw["text"])} {_badge(hw.get("confidence"))} '
              f'<span class="fact-meta">{_link_meta(ctx, hw)}</span></p>') if hw.get("text") else ""
    if not links:
        if r.get("tier") != "A" and not window:
            return ""
        return (f'<section class="panel-section jobs"><h3>Jobs</h3>{window}'
                '<p class="not-verified">Jobs links are being collected.</p></section>')
    groups = []
    for key, title in JOB_GROUPS:
        items = [x for x in links if x.get("role_group") == key]
        if not items:
            continue
        lis = []
        for x in items:
            tags = "".join(f'<span class="tag">{_esc(DISCIPLINE_LABEL.get(d, d))}</span>' for d in x.get("disciplines") or [])
            tags = f' <span class="job-tags"><span class="visually-hidden">Disciplines: </span>{tags}</span>' if tags else ""
            lis.append(f'<li><a class="job-link" href="{_esc(x["url"])}" {NEW_TAB}>{_esc(x["label"])}</a> {_badge(x.get("confidence"))}'
                       f'{tags}<span class="fact-meta">{_link_meta(ctx, x)}</span></li>')
        groups.append(f'<div class="job-group" data-group="{key}"><h4 class="sub">{_esc(title)}</h4>'
                      f'<ul class="job-links">{"".join(lis)}</ul></div>')
    return ('<section class="panel-section jobs"><h3>Jobs</h3>' + window +
            '<p class="fact-meta">Links open each employer\'s own site in a new tab.</p>' + "".join(groups) + "</section>")


def render_resort(ctx: Ctx, r: dict, c: dict, st: str) -> str:
    st_name = ctx.state_names.get(st.upper(), st)
    crumbs = _crumbs([("United States", "/map/"), (st_name, f"/map/{st}/"), (c["name"], f"/map/{st}/{c['id']}/"), (r["name"], None)])
    tags = [f'<span class="tier tier-{"a" if r["tier"] == "A" else "b"}">Tier {r["tier"]}</span>',
            f'<span class="tier tier-facility">{_esc(FACILITY_LABEL.get(r.get("facility_type") or "ski_area", "Ski area"))}</span>']
    if r["tier"] == "A" and r.get("tier_a_status") == "approved":
        tags.append('<span class="tier tier-approved">Approved</span>')
    elif r["tier"] == "A" and r.get("tier_a_status") == "draft":
        tags.append('<span class="tier tier-draft">Draft profile</span>')
    otm = r.get("official_trailmap") or {}
    otm_html = ""
    if str(otm.get("url", "")).startswith("https://"):
        fmt = {"pdf": "PDF", "jpg": "JPG image", "png": "PNG image", "page": "Web page"}.get(otm.get("format"), "")
        bits = " · ".join(x for x in (fmt, f"{otm['season']} season" if otm.get("season") else "", "opens in a new tab") if x)
        otm_html = (f'<p class="official-trailmap"><a class="official-trailmap-link" href="{_esc(otm["url"])}" target="_blank" '
                    f'rel="noopener noreferrer">Official trail map from {_esc(r["name"])}</a> <span class="fact-meta">{_esc(bits)}</span></p>')
    out = [crumbs, _heading(f"Resort in {c['name']}, {r['state'].upper()}", r["name"]),
           f'<div class="tier-row">{"".join(tags)}</div>', otm_html, render_webcams(ctx, r),
           f'<dl class="facts">{_sourced(ctx, "Owner", r.get("owner"), str)}</dl>']
    crit = r.get("tier_a_criteria") or []
    if r["tier"] == "A" and crit:
        lis = "".join(f'<li><span class="criterion">{_esc(CRITERION_LABEL.get(k["criterion"], k["criterion"]))}</span>'
                      f'<span class="fact-meta">{_source_link(ctx, k.get("source_id"))}</span></li>' for k in crit)
        out.append(f'<section class="panel-section"><h3>Why Tier A</h3><ul class="criteria">{lis}</ul></section>')
    out.append(resort_editorial(ctx, r))
    size, elev, season = r.get("size") or {}, r.get("elevation") or {}, r.get("season") or {}
    out.append('<section class="panel-section"><h3>Operation size</h3><dl class="facts">'
               + _sourced(ctx, "Skiable acres", size.get("acres"), _num)
               + _sourced(ctx, "Vertical drop", size.get("vertical_ft"), lambda v: f"{_num(v)} ft")
               + _sourced(ctx, "Base elevation", elev.get("base_ft"), lambda v: f"{_num(v)} ft")
               + _sourced(ctx, "Summit elevation", elev.get("summit_ft"), lambda v: f"{_num(v)} ft")
               + _sourced(ctx, "Lifts", size.get("lifts"), _num) + "</dl></section>")
    out.append('<section class="panel-section"><h3>Season</h3><dl class="facts">'
               + _sourced(ctx, "Typical opening", season.get("open_typical"), _month_day)
               + _sourced(ctx, "Typical closing", season.get("close_typical"), _month_day)
               + _sourced(ctx, "Season length", season.get("length_days"), lambda v: f"{_num(v)} days") + "</dl></section>")
    career = r.get("career")
    if not career:
        out.append('<section class="panel-section"><h3>Career</h3><p class="not-verified">Career data is being collected.</p></section>')
    else:
        rows = career.get("pay") or []
        if rows:
            trs = []
            for row in rows:
                lo, hi = row.get("hourly_low"), row.get("hourly_high")
                if lo is None and hi is None:
                    rng = "Not yet verified"
                elif lo is None or hi is None or lo == hi:
                    rng = _money(lo if lo is not None else hi, True)
                else:
                    rng = f"{_money(lo, True)} to {_money(hi, True)}"
                conf = row.get("confidence", "")
                trs.append(f'<tr><th scope="row">{_esc(CERT_LABEL.get(row["cert_level"], row["cert_level"]))}</th>'
                           f'<td>{_esc(rng)} <span class="badge badge-{_esc(conf)}">{_esc(CONFIDENCE_LABEL.get(conf, conf))}</span> '
                           f'<span class="fact-meta">Last verified {_esc(_date(row.get("as_of")))} · {_source_link(ctx, row.get("source_id"))}</span></td></tr>')
            pay = ('<table class="pay-table"><caption class="visually-hidden">Hourly pay by certification level</caption>'
                   '<thead><tr><th scope="col">Certification</th><th scope="col">Hourly pay</th></tr></thead>'
                   f'<tbody>{"".join(trs)}</tbody></table>')
        else:
            pay = '<p class="not-verified">Not yet verified</p>'
        out.append(f'<section class="panel-section"><h3>Career</h3><p class="sub">Hourly pay by certification</p>{pay}</section>')
    out.append(render_jobs(ctx, r))
    out.append(_footer())
    return "".join(x for x in out if x)


def render_cluster(ctx: Ctx, c: dict, st: str) -> str:
    st_name = ctx.state_names.get(st.upper(), st)
    resorts = [ctx.resorts[i] for i in c["resort_ids"] if i in ctx.resorts]
    resorts.sort(key=lambda r: (r["tier"] != "A", r["name"]))
    lis = "".join(
        f'<li><a class="nav-item" href="/map/{st}/{c["id"]}/{r["id"]}/"><span class="nav-name">{_esc(r["name"])}'
        + (' <span class="tier tier-a">Tier A</span>' if r["tier"] == "A" else "") + "</span></a></li>"
        for r in resorts) if resorts else ""
    states = _join_and([ctx.state_names.get(s, s) for s in c["states"]])
    return "".join([
        _crumbs([("United States", "/map/"), (st_name, f"/map/{st}/"), (c["name"], None)]),
        _heading("Cluster", c["name"]),
        f'<p class="intro">{_esc(_plural(len(resorts), "resort", "resorts"))} in {_esc(states)}, '
        f'{_esc(_plural(c.get("tier_a_count", 0), "Tier A resort", "Tier A resorts"))}.</p>',
        cluster_editorial(ctx, c),
        f'<section class="panel-section"><h3>Resorts</h3><ul class="nav-list">{lis}</ul></section>',
        _footer(),
    ])


