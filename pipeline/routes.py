"""Generate static route stubs for Career Map deep links.

GitHub Pages has no rewrites, so every deep link needs a real file. Each stub is
a copy of /map/index.html with its own <title>, meta description and canonical
URL. The map JavaScript reads the path and renders the right view.

    /map/{state}/index.html
    /map/{state}/{cluster}/index.html
    /map/{state}/{cluster}/{resort}/index.html

A cluster that spans states gets a stub under every one of its states; the
canonical URL uses the first state in cluster.states. A resort's canonical URL
uses the resort's own state when that state is one of the cluster's states.

Generated pages are listed in /map/.routes-manifest.json and carry a marker
comment. Stale stubs are removed on the next run. /map/index.html, /map/js,
/map/css and /map/vendor are never touched.

Keep the title and description wording in step with map/js/meta.js.

    python pipeline/routes.py            # uses this repository
    python pipeline/routes.py --root DIR # any directory with data/build and map/index.html
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

SITE = "https://instructorgrindset.com"
MARKER = "<!-- route stub generated by pipeline/routes.py from map/index.html; do not edit -->"
MANIFEST_NAME = ".routes-manifest.json"
PROTECTED = frozenset({"js", "css", "vendor", "index.html", MANIFEST_NAME})
SUFFIX = "Snowsports Career Map"

STATE_RE = re.compile(r"^[a-z]{2}$")
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
TITLE_RE = re.compile(r"<title>.*?</title>", re.S)
DESC_RE = re.compile(r'(<meta\s+name="description"\s+content=")[^"]*(")', re.S)
CANON_RE = re.compile(r'(<link\s+rel="canonical"\s+href=")[^"]*(")', re.S)
REF_RE = re.compile(r'\b(?:src|href)="([^"]*)"')


def _plural(n: int, one: str, many: str) -> str:
    return f"{n:,} {one if n == 1 else many}"


def _join_and(items: list[str]) -> str:
    if len(items) <= 1:
        return "".join(items)
    return f"{', '.join(items[:-1])} and {items[-1]}"


def state_meta(state: dict) -> tuple[str, str]:
    return (
        f"{state['name']} Resorts and Clusters • {SUFFIX}",
        f"Explore the snowsports resort clusters in {state['name']}. See season dates, snowfall, "
        f"and operation size for {_plural(state['resort_count'], 'resort', 'resorts')}, with a source on every number.",
    )


def cluster_meta(cluster: dict, state_names: dict[str, str]) -> tuple[str, str]:
    names = _join_and([state_names.get(s, s) for s in cluster["states"]])
    return (
        f"{cluster['name']} Cluster • {SUFFIX}",
        f"Explore the {_plural(len(cluster['resort_ids']), 'resort', 'resorts')} of the {cluster['name']} cluster "
        f"in {names}. Compare season length, snowfall, powder days, and operation size, with a source on every number.",
    )


def resort_meta(resort: dict, cluster: dict, state_names: dict[str, str]) -> tuple[str, str]:
    return (
        f"{resort['name']}: Season, Snow and Size • {SUFFIX}",
        f"Plan a season at {resort['name']} in the {cluster['name']} cluster, "
        f"{state_names.get(resort['state'].upper(), resort['state'])}. See season dates, snowfall by month, "
        "powder days, terrain, and operation size, with a source on every number.",
    )


def _load(build: Path, name: str):
    path = build / name
    if not path.exists():
        raise FileNotFoundError(f"{path} is missing; run pipeline/build.py first")
    return json.loads(path.read_text(encoding="utf-8"))


def plan_pages(build: Path) -> dict[str, tuple[str, str, str]]:
    """Map of stub directory (relative to /map/, with trailing slash) to (title, description, canonical path)."""
    resorts = _load(build, "resorts.json")["resorts"]
    clusters = [f["properties"] for f in _load(build, "clusters.geojson")["features"]]
    states = _load(build, "states.json")["states"]

    state_names = {s["code"].upper(): s["name"] for s in states}
    valid_states = {c for c in state_names if STATE_RE.match(c.lower()) and c.lower() not in PROTECTED}
    pages: dict[str, tuple[str, str, str]] = {}

    def warn(msg: str) -> None:
        print(f"routes: skipping {msg}", file=sys.stderr)

    for s in states:
        code = s["code"].upper()
        if code not in valid_states:
            warn(f"state code {code!r}")
            continue
        rel = f"{code.lower()}/"
        pages[rel] = (*state_meta(s), f"/map/{rel}")

    cluster_by_id: dict[str, dict] = {}
    for c in clusters:
        cid = c.get("id", "")
        if not SLUG_RE.match(cid):
            warn(f"cluster id {cid!r}")
            continue
        sts = [x.upper() for x in c.get("states", []) if x.upper() in valid_states]
        if not sts:
            warn(f"cluster {cid!r} with no known state")
            continue
        c = {**c, "states": sts}
        cluster_by_id[cid] = c
        title, desc = cluster_meta(c, state_names)
        canonical = f"/map/{sts[0].lower()}/{cid}/"
        for st in sts:
            pages[f"{st.lower()}/{cid}/"] = (title, desc, canonical)

    for r in resorts:
        rid = r.get("id", "")
        if not SLUG_RE.match(rid):
            warn(f"resort id {rid!r}")
            continue
        c = cluster_by_id.get(r.get("cluster_id"))
        if not c:
            warn(f"resort {rid!r} in unknown cluster {r.get('cluster_id')!r}")
            continue
        title, desc = resort_meta(r, c, state_names)
        home = r["state"].upper() if r["state"].upper() in c["states"] else c["states"][0]
        canonical = f"/map/{home.lower()}/{c['id']}/{rid}/"
        for st in c["states"]:
            pages[f"{st.lower()}/{c['id']}/{rid}/"] = (title, desc, canonical)
    return pages


def check_template(template: str) -> None:
    if MARKER in template:
        raise ValueError("map/index.html is itself a generated stub; restore the hand written shell")
    for pattern, what in ((TITLE_RE, "<title>"), (DESC_RE, "meta description"), (CANON_RE, "canonical link")):
        if not pattern.search(template):
            raise ValueError(f"map/index.html has no {what}")
    for ref in REF_RE.findall(template):
        if not (ref.startswith("/") or ref.startswith("https://") or ref.startswith("http://") or ref.startswith("#")):
            raise ValueError(f"map/index.html uses relative path {ref!r}; stubs need absolute paths")


def render_stub(template: str, title: str, description: str, canonical_path: str) -> str:
    out = TITLE_RE.sub(lambda _: f"<title>{html.escape(title, quote=False)}</title>", template, count=1)
    out = DESC_RE.sub(lambda m: f"{m.group(1)}{html.escape(description)}{m.group(2)}", out, count=1)
    out = CANON_RE.sub(lambda m: f"{m.group(1)}{html.escape(SITE + canonical_path)}{m.group(2)}", out, count=1)
    return out.replace("<head>", f"<head>\n  {MARKER}", 1)


def _is_protected(rel: str) -> bool:
    first = rel.strip("/").split("/", 1)[0]
    return not first or first in PROTECTED


def _remove_stub(map_dir: Path, rel: str) -> bool:
    """Delete a generated index.html and any directories left empty. Returns True when removed."""
    if _is_protected(rel):
        return False
    target_dir = (map_dir / rel).resolve()
    root = map_dir.resolve()
    if root not in target_dir.parents:
        return False
    page = target_dir / "index.html"
    if not page.is_file() or page.is_symlink():
        return False
    if MARKER not in page.read_text(encoding="utf-8", errors="replace"):
        return False
    page.unlink()
    d = target_dir
    while d != root and root in d.parents and not _is_protected(str(d.relative_to(root))):
        try:
            d.rmdir()  # only succeeds when empty
        except OSError:
            break
        d = d.parent
    return True


def _scan_generated(map_dir: Path) -> set[str]:
    """Stub pages on disk that carry the marker (covers a lost manifest)."""
    found = set()
    for page in map_dir.glob("*/**/index.html"):
        rel = page.parent.relative_to(map_dir).as_posix() + "/"
        if _is_protected(rel) or page.is_symlink():
            continue
        try:
            if MARKER in page.read_text(encoding="utf-8", errors="replace"):
                found.add(rel)
        except OSError:
            continue
    return found


def generate_routes(repo_root: Path) -> int:
    """Write every stub, remove stale ones, update the manifest. Returns the number of stub pages."""
    repo_root = Path(repo_root)
    map_dir = repo_root / "map"
    template = (map_dir / "index.html").read_text(encoding="utf-8")
    check_template(template)
    pages = plan_pages(repo_root / "data" / "build")

    manifest_path = map_dir / MANIFEST_NAME
    previous: set[str] = set()
    if manifest_path.exists():
        try:
            previous = set(json.loads(manifest_path.read_text(encoding="utf-8")).get("pages", []))
        except (json.JSONDecodeError, AttributeError):
            previous = set()
    previous |= _scan_generated(map_dir)

    for rel in sorted(previous - set(pages), key=lambda p: -p.count("/")):
        _remove_stub(map_dir, rel)

    for rel, (title, desc, canonical) in sorted(pages.items()):
        out_dir = map_dir / rel
        if _is_protected(rel):
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        page = out_dir / "index.html"
        content = render_stub(template, title, desc, canonical)
        if page.exists() and MARKER not in page.read_text(encoding="utf-8", errors="replace"):
            raise RuntimeError(f"{page} exists and was not generated by routes.py; refusing to overwrite")
        if not page.exists() or page.read_text(encoding="utf-8") != content:
            page.write_text(content, encoding="utf-8")

    manifest_path.write_text(json.dumps({
        "generated_by": "pipeline/routes.py",
        "note": "Route stubs under /map/. Regenerate with python pipeline/routes.py; do not edit by hand.",
        "pages": sorted(pages),
    }, indent=2) + "\n", encoding="utf-8")
    return len(pages)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="directory holding data/build and map/index.html (default: this repository)")
    args = parser.parse_args(argv)
    try:
        n = generate_routes(args.root)
    except (FileNotFoundError, ValueError, RuntimeError) as err:
        print(f"routes: {err}", file=sys.stderr)
        return 1
    print(f"routes: wrote {n} stub pages under {args.root / 'map'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
