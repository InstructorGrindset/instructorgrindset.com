# ── JSON-LD ──

def _breadcrumbs(items: list[tuple[str, str]]) -> dict:
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": name, "item": SITE + path} for i, (name, path) in enumerate(items)]}


def resort_jsonld(r: dict, c: dict, canonical: str, ctx: Ctx) -> dict:
    st = canonical.split("/")[2]
    kind = "SkiResort" if (r.get("facility_type") or "ski_area") == "ski_area" else "SportsActivityLocation"
    place = {"@type": kind, "name": r["name"], "url": SITE + canonical,
             "geo": {"@type": "GeoCoordinates", "latitude": r["lat"], "longitude": r["lon"]},
             "address": {"@type": "PostalAddress", "addressRegion": r["state"].upper(), "addressCountry": "US"},
             "containedInPlace": {"@type": "Place", "name": c["name"]}}
    return {"@context": "https://schema.org", "@graph": [place, _breadcrumbs([
        ("Snowsports Career Map", "/map/"), (ctx.state_names.get(st.upper(), st), f"/map/{st}/"),
        (c["name"], f"/map/{st}/{c['id']}/"), (r["name"], canonical)])]}


def list_jsonld(name: str, canonical: str, items: list[tuple[str, str]], crumbs: list[tuple[str, str]]) -> dict:
    return {"@context": "https://schema.org", "@graph": [
        {"@type": "CollectionPage", "name": name, "url": SITE + canonical, "mainEntity": {
            "@type": "ItemList", "itemListElement": [
                {"@type": "ListItem", "position": i + 1, "name": n, "url": SITE + p} for i, (n, p) in enumerate(items)]}},
        _breadcrumbs(crumbs)]}


# ── Planning ──

@dataclass
class Page:
    title: str
    description: str
    canonical: str
    body: str = ""
    jsonld: dict = field(default_factory=dict)
    record: Optional[dict] = None
    in_sitemap: bool = True


def _load(build: Path, name: str, optional: bool = False):
    path = build / name
    if not path.exists():
        if optional:
            return None
        raise FileNotFoundError(f"{path} is missing; run pipeline/build.py first")
    return json.loads(path.read_text(encoding="utf-8"))


def plan_pages(build: Path) -> dict[str, Page]:
    """Map of page directory (relative to /map/, trailing slash) to its Page."""
    resorts = _load(build, "resorts.json")["resorts"]
    clusters = [f["properties"] for f in _load(build, "clusters.geojson")["features"]]
    states = _load(build, "states.json")["states"]
    sources_file = _load(build, "sources.json", optional=True) or {"sources": []}

    state_names = {s["code"].upper(): s["name"] for s in states}
    valid_states = {c for c in state_names if STATE_RE.match(c.lower()) and c.lower() not in PROTECTED}
    pages: dict[str, Page] = {}

    def warn(msg: str) -> None:
        print(f"routes: skipping {msg}", file=sys.stderr)

    cluster_by_id: dict[str, dict] = {}
    for c in clusters:
        cid = c.get("id", "")
        if not SLUG_RE.match(cid):
            warn(f"cluster id {cid!r}")
            continue
        sts = [x.upper() for x in c.get("states", []) if x.upper() in valid_states]
        if not sts:
            warn(f"cluster {cid!r} with no known state")
            continue
        cluster_by_id[cid] = {**c, "states": sts}

    resort_by_id = {r["id"]: r for r in resorts if SLUG_RE.match(r.get("id", ""))}
    for r in resorts:
        if r.get("id") not in resort_by_id:
            warn(f"resort id {r.get('id')!r}")
    ctx = Ctx({s["id"]: s for s in sources_file.get("sources", [])}, state_names, cluster_by_id, resort_by_id)

    names = [r["name"] for r in resort_by_id.values()]
    duplicate_names = {n for n in names if names.count(n) > 1}

    def resort_canonical(r: dict, c: dict) -> str:
        home = r["state"].upper() if r["state"].upper() in c["states"] else c["states"][0]
        return f"/map/{home.lower()}/{c['id']}/{r['id']}/"

    for s in states:
        code = s["code"].upper()
        if code not in valid_states:
            warn(f"state code {code!r}")
            continue
        st = code.lower()
        title, desc = state_meta(s)
        canonical = f"/map/{st}/"
        cl = [cluster_by_id[i] for i in s.get("cluster_ids", []) if i in cluster_by_id]
        pages[f"{st}/"] = Page(title, desc, canonical, render_state(ctx, s), list_jsonld(
            title, canonical, [(c["name"], f"/map/{st}/{c['id']}/") for c in cl],
            [("Snowsports Career Map", "/map/"), (s["name"], canonical)]))

    for cid, c in cluster_by_id.items():
        title, desc = cluster_meta(c, state_names)
        canonical = f"/map/{c['states'][0].lower()}/{cid}/"
        members = [resort_by_id[i] for i in c.get("resort_ids", []) if i in resort_by_id and resort_by_id[i].get("cluster_id") == cid]
        for st_code in c["states"]:
            st = st_code.lower()
            pages[f"{st}/{cid}/"] = Page(title, desc, canonical, render_cluster(ctx, c, st), list_jsonld(
                title, canonical, [(r["name"], resort_canonical(r, c)) for r in members],
                [("Snowsports Career Map", "/map/"), (state_names[st_code], f"/map/{st}/"), (c["name"], canonical)]))

    for r in resort_by_id.values():
        c = cluster_by_id.get(r.get("cluster_id"))
        if not c:
            warn(f"resort {r['id']!r} in unknown cluster {r.get('cluster_id')!r}")
            continue
        title, desc = resort_meta(r, c, state_names, duplicate_names)
        canonical = resort_canonical(r, c)
        jsonld = resort_jsonld(r, c, canonical, ctx)
        record = resort_record(ctx, r, sources_file)
        for st_code in c["states"]:
            st = st_code.lower()
            # The sitemap lists Tier A resorts only; Tier B pages exist and stay crawlable.
            pages[f"{st}/{c['id']}/{r['id']}/"] = Page(title, desc, canonical, render_resort(ctx, r, c, st), jsonld, record,
                                                      in_sitemap=r.get("tier") == "A")
    return pages


# ── Slim national index (map first paint) ──

INDEX_NAME = "map-index.json"
INDEX_FIELDS = ("id", "name", "tier", "tier_a_status", "facility_type", "state", "cluster_id", "lat", "lon",
                "acres", "size_rank", "climate_available", "detail_available", "webcams_available", "jobs_available",
                "season_length_days", "snowfall_annual_in", "lucrativeness_mid", "hiring_window", "job_employers")
RECOLOR_PROPS = ("season_length_days", "snowfall_annual_in", "lucrativeness_mid")


def _size_breaks() -> Optional[list[float]]:
    """display.size_rank_acres_breaks from config/definitions.yaml (the same breaks build.py uses)."""
    try:
        import yaml  # noqa: PLC0415 (only needed when resorts.geojson lacks size_rank)
        cfg = yaml.safe_load((Path(__file__).resolve().parents[1] / "config" / "definitions.yaml").read_text(encoding="utf-8"))
        breaks = cfg["display"]["size_rank_acres_breaks"]
        return [float(b) for b in breaks]
    except Exception:  # noqa: BLE001
        return None


def size_rank(acres: Optional[float], breaks: Optional[list[float]]) -> int:
    """1 to 5 from skiable acres: 1 + number of breaks at or below acres. Null acres or no breaks gives 1."""
    if acres is None or not breaks:
        return 1
    return 1 + sum(1 for b in breaks if acres >= b)


def _value(src: Any) -> Any:
    return src.get("value") if isinstance(src, dict) else None


def _hiring_index(r: dict, feed_ids: Optional[set]) -> tuple[Optional[list], Optional[list]]:
    """The "Hiring now" filter's two index values: hiring_window [start_month, end_month] (read from the text by
    pipeline/hiring.py) or null, and job_employers, the linked employers whose board feeds jobs/postings.json
    (every linked employer without jobs/employers.json), or null."""
    jobs = r.get("jobs") or {}
    hw = jobs.get("hiring_window") or {}
    window = [hw["start_month"], hw["end_month"]] if hw.get("start_month") and hw.get("end_month") else None
    ids = {x["employer_id"] for x in jobs.get("links") or [] if x.get("employer_id")} if jobs.get("feed") else set()
    ids = sorted(ids if feed_ids is None else ids & feed_ids)
    return window, ids or None


def build_map_index(build: Path) -> dict:
    """Slim rows from resorts.json plus the recolor values from resorts.geojson (when present).

    Every value is copied from the build output. size_rank comes from resorts.geojson; without it, from the
    config breaks build.py uses.
    """
    meta = _load(build, "resorts.json")
    geo = _load(build, "resorts.geojson", optional=True) or {"features": []}
    props = {f["properties"]["id"]: f["properties"] for f in geo.get("features", [])
             if isinstance(f, dict) and isinstance(f.get("properties"), dict) and f["properties"].get("id")}
    employers = _load(build, "jobs/employers.json", optional=True)
    feed_ids = {e["id"] for e in employers.get("employers", []) if e.get("feed")} if employers else None
    rows = []
    breaks: Any = False  # loaded on first need
    for r in meta.get("resorts", []):
        if not SLUG_RE.match(str(r.get("id", ""))) or r.get("lat") is None or r.get("lon") is None:
            continue
        p = props.get(r["id"], {})
        size, season, career = r.get("size") or {}, r.get("season") or {}, r.get("career") or {}
        acres = _value(size.get("acres"))
        derived = {
            "season_length_days": _value(season.get("length_days")),
            "snowfall_annual_in": None,
            "lucrativeness_mid": (career.get("lucrativeness") or {}).get("mid"),
        }
        rank = p.get("size_rank")
        if not isinstance(rank, int):
            if breaks is False:
                breaks = _size_breaks()
            rank = size_rank(acres, breaks)
        row = {
            "id": r["id"], "name": r["name"], "tier": r["tier"], "tier_a_status": r.get("tier_a_status"),
            "facility_type": r.get("facility_type") or "ski_area", "state": r["state"], "cluster_id": r["cluster_id"],
            "lat": r["lat"], "lon": r["lon"], "acres": acres,
            "size_rank": rank,
            "climate_available": bool(r.get("climate_available")), "detail_available": bool(r.get("detail_available")),
            "webcams_available": bool(r.get("webcams")), "jobs_available": bool((r.get("jobs") or {}).get("links")),
        }
        row["hiring_window"], row["job_employers"] = _hiring_index(r, feed_ids)
        for k in RECOLOR_PROPS:
            row[k] = p[k] if k in p else derived[k]
        rows.append({k: row[k] for k in INDEX_FIELDS})
    return {"version": meta.get("version", 1), "generated_at": meta.get("generated_at"), "fields": list(INDEX_FIELDS),
            "resorts": [[row[k] for k in INDEX_FIELDS] for row in rows]}


def write_map_index(build: Path) -> Path:
    """Write data/build/map-index.json (compact, rows as arrays in `fields` order). Returns its path."""
    path = Path(build) / INDEX_NAME
    text = json.dumps(build_map_index(Path(build)), ensure_ascii=False, separators=(",", ":")) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
    return path


def resort_record(ctx: Ctx, r: dict, sources_file: dict) -> dict:
    """The resort's resorts.json record plus the sources it cites, embedded in its page."""
    cited = set(r.get("sources") or [])
    e = r.get("editorial")
    if e and (not isinstance(e, dict) or e.get("status") != "reviewed"):
        r = {**r, "editorial": None}  # drafts never reach a page, even inside data
    return {"version": 1, "generated_at": sources_file.get("generated_at"), "resort": r,
            "sources": [ctx.sources[i] for i in sorted(cited) if i in ctx.sources]}


# ── Rendering ──

def check_template(template: str) -> None:
    if MARKER in template:
        raise ValueError("map/index.html is itself a generated stub; restore the hand written shell")
    checks = [(TITLE_RE, "<title>"), (DESC_RE, "meta description"), (CANON_RE, "canonical link"),
              (PRERENDER_RE, "prerender markers")] + [(rx, f"og:{k} meta tag") for k, rx in OG_RE.items()]
    for pattern, what in checks:
        if not pattern.search(template):
            raise ValueError(f"map/index.html has no {what}")
    for ref in REF_RE.findall(template):
        if not ref.startswith(("/", "https://", "http://", "#", "data:")):
            raise ValueError(f"map/index.html uses relative path {ref!r}; stubs need absolute paths")


def _jsonld_script(data: dict) -> str:
    # Escape every "<" so data can never close the script element.
    raw = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    return f'<script type="application/ld+json">{raw}</script>'


def render_stub(template: str, page: Page) -> str:
    title, description = page.title, page.description
    url = SITE + page.canonical
    out = TITLE_RE.sub(lambda _: f"<title>{html.escape(title, quote=False)}</title>", template, count=1)
    out = DESC_RE.sub(lambda m: f"{m.group(1)}{html.escape(description)}{m.group(2)}", out, count=1)
    out = CANON_RE.sub(lambda m: f"{m.group(1)}{html.escape(url)}{m.group(2)}", out, count=1)
    og = {"title": title.split(" • ")[0], "description": description, "url": url}
    for key, rx in OG_RE.items():
        out = rx.sub(lambda m, v=og[key]: f"{m.group(1)}{html.escape(v)}{m.group(2)}", out, count=1)
    if page.body:
        out = PRERENDER_RE.sub(lambda m: f"{m.group(1)}\n{page.body}\n{m.group(2)}", out, count=1)
    if page.jsonld:
        out = out.replace("</head>", f"  {_jsonld_script(page.jsonld)}\n</head>", 1)
    if page.record:
        raw = json.dumps(page.record, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
        out = out.replace("</head>", f'  <script type="application/json" id="resort-record">{raw}</script>\n'
                          '  <link rel="modulepreload" href="/map/js/schemas.js">\n'
                          '  <link rel="modulepreload" href="/map/vendor/zod/zod.mjs">\n</head>', 1)
    return out.replace("<head>", f"<head>\n  {MARKER}", 1)


# ── Stale page cleanup ──

def _is_protected(rel: str) -> bool:
    first = rel.strip("/").split("/", 1)[0]
    return not first or first in PROTECTED


def _remove_stub(map_dir: Path, rel: str) -> bool:
    """Delete a generated index.html and any directories left empty. Returns True when removed."""
    if _is_protected(rel):
        return False
    target_dir = (map_dir / rel).resolve()
    root = map_dir.resolve()
    if root not in target_dir.parents:
        return False
    page = target_dir / "index.html"
    if not page.is_file() or page.is_symlink():
        return False
    if MARKER not in page.read_text(encoding="utf-8", errors="replace"):
        return False
    page.unlink()
    d = target_dir
    while d != root and root in d.parents and not _is_protected(str(d.relative_to(root))):
        try:
            d.rmdir()  # only succeeds when empty
        except OSError:
            break
        d = d.parent
    return True


def _scan_generated(map_dir: Path) -> set[str]:
    """Stub pages on disk that carry the marker (covers a lost manifest)."""
    found = set()
    for page in map_dir.glob("*/**/index.html"):
        rel = page.parent.relative_to(map_dir).as_posix() + "/"
        if _is_protected(rel) or page.is_symlink():
            continue
        try:
            if MARKER in page.read_text(encoding="utf-8", errors="replace"):
                found.add(rel)
        except OSError:
            continue
    return found


# ── Sitemap ──

def update_sitemap(path: Path, canonical_paths: list[str], lastmod: Optional[str]) -> int:
    """Rewrite only the /map/ entries of sitemap.xml; keep every other entry byte for byte. Returns map entry count."""
    head = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
    text = path.read_text(encoding="utf-8") if path.exists() else f"{head}\n</urlset>\n"
    start = text.find("<urlset")
    open_end = text.find(">", start) + 1
    close = text.rfind("</urlset>")
    if start < 0 or close < 0:
        raise ValueError(f"{path} is not a sitemap urlset")
    kept = [u.strip() for u in SITEMAP_URL_RE.findall(text[open_end:close])
            if f"<loc>{SITE}/map/" not in u]
    paths = ["/map/"] + sorted(p for p in set(canonical_paths) if p != "/map/")

    def entry(p: str) -> str:
        depth = p.strip("/").count("/")
        priority = {0: "0.8", 1: "0.6", 2: "0.6", 3: "0.7"}.get(depth, "0.5")
        lm = f"\n    <lastmod>{lastmod}</lastmod>" if lastmod else ""
        return f"<url>\n    <loc>{SITE}{p}</loc>{lm}\n    <priority>{priority}</priority>\n  </url>"

    body = "\n  ".join(kept + [entry(p) for p in paths])
    new = f"{text[:open_end]}\n  {body}\n{text[close:]}"
    if not new.endswith("\n"):
        new += "\n"
    if new != text:
        path.write_text(new, encoding="utf-8")
    return len(paths)


# ── Entry point ──

def generate_routes(repo_root: Path, sitemap: bool = True) -> int:
    """Write every page, remove stale ones, update the manifest and sitemap. Returns the number of pages."""
    repo_root = Path(repo_root)
    map_dir = repo_root / "map"
    template = (map_dir / "index.html").read_text(encoding="utf-8")
    check_template(template)
    build = repo_root / "data" / "build"
    pages = plan_pages(build)
    write_map_index(build)

    manifest_path = map_dir / MANIFEST_NAME
    previous: set[str] = set()
    if manifest_path.exists():
        try:
            previous = set(json.loads(manifest_path.read_text(encoding="utf-8")).get("pages", []))
        except (json.JSONDecodeError, AttributeError):
            previous = set()
    previous |= _scan_generated(map_dir)

    for rel in sorted(previous - set(pages), key=lambda p: -p.count("/")):
        _remove_stub(map_dir, rel)

    for rel, page in sorted(pages.items()):
        if _is_protected(rel):
            continue
        out_dir = map_dir / rel
        out_dir.mkdir(parents=True, exist_ok=True)
        target = out_dir / "index.html"
        content = render_stub(template, page)
        if target.exists() and MARKER not in target.read_text(encoding="utf-8", errors="replace"):
            raise RuntimeError(f"{target} exists and was not generated by routes.py; refusing to overwrite")
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")

    manifest_path.write_text(json.dumps({
        "generated_by": "pipeline/routes.py",
        "note": "Route pages under /map/. Regenerate with python pipeline/routes.py; do not edit by hand.",
        "pages": sorted(pages),
    }, indent=2) + "\n", encoding="utf-8")

    if sitemap:
        meta = _load(build, "resorts.json")
        lastmod = str(meta.get("generated_at", ""))[:10] or None
        static = [f"/map/{rel}" for rel in STATIC_PAGES if (map_dir / rel / "index.html").is_file()]
        update_sitemap(repo_root / "sitemap.xml", [p.canonical for p in pages.values() if p.in_sitemap] + static, lastmod)
    return len(pages)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="directory holding data/build and map/index.html (default: this repository)")
    parser.add_argument("--no-sitemap", action="store_true", help="leave sitemap.xml untouched")
    args = parser.parse_args(argv)
    try:
        n = generate_routes(args.root, sitemap=not args.no_sitemap)
    except (FileNotFoundError, ValueError, RuntimeError) as err:
        print(f"routes: {err}", file=sys.stderr)
        return 1
    print(f"routes: wrote {n} stub pages under {args.root / 'map'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
