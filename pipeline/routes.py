# ── Prerendered HTML ──

@dataclass
class Ctx:
    sources: dict[str, dict]
    state_names: dict[str, str]
    clusters: dict[str, dict]
    resorts: dict[str, dict]


def _source_link(ctx: Ctx, source_id: Optional[str]) -> str:
    s = ctx.sources.get(source_id or "")
    if not s:
        return ""
    url = s.get("url", "")
    title = _esc(s.get("title") or source_id)
    if url.startswith(("https://", "http://")):
        return f'<a class="src-link" href="{_esc(url)}" rel="noopener noreferrer">{title}</a>'
    return title


def _sourced(ctx: Ctx, label: str, src: Optional[dict], fmt) -> str:
    if not src:
        return f'<div class="fact"><dt>{_esc(label)}</dt><dd><span class="not-verified">Not yet verified</span></dd></div>'
    conf = src.get("confidence", "")
    link = _source_link(ctx, src.get("source_id"))
    meta = f"Last verified {_esc(_date(src.get('as_of')))}" + (f" · {link}" if link else "")
    return (f'<div class="fact"><dt>{_esc(label)}</dt><dd><span class="sourced"><span class="sourced-main">'
            f'<span class="fact-value">{_esc(fmt(src["value"]))}</span> '
            f'<span class="badge badge-{_esc(conf)}">{_esc(CONFIDENCE_LABEL.get(conf, conf))}</span></span>'
            f'<span class="fact-meta">{meta}</span></span></dd></div>')


def _crumbs(items: list[tuple[str, Optional[str]]]) -> str:
    lis = "".join(
        f'<li><a href="{_esc(href)}">{_esc(label)}</a></li>' if href else f'<li><span aria-current="page">{_esc(label)}</span></li>'
        for label, href in items)
    return f'<nav class="crumbs" aria-label="Breadcrumb"><ol>{lis}</ol></nav>'


def _heading(eyebrow: str, text: str) -> str:
    return f'<span class="eyebrow">{_esc(eyebrow)}</span><h2 id="panel-heading" tabindex="-1">{_esc(text)}</h2>'


def _footer() -> str:
    related = "".join(f'<li><a href="{href}">{_esc(label)}</a></li>' for href, label in RELATED)
    return ('<footer class="panel-footer"><p>Choosing your next mountain? Talk it through with Alexandre.</p>'
            f'<a class="btn btn-sm" href="{CONSULT_URL}">Book a Free Consultation</a>'
            f'<nav class="related" aria-label="Related tools and reading"><p class="sub">Keep planning</p><ul>{related}</ul></nav>'
            f'<p class="fact-meta credits-link"><a href="{CREDITS_URL}">Sources and credits</a></p></footer>')


def _markdown(md: str) -> str:
    """Small, safe Markdown subset for reviewed editorial: paragraphs, **bold**, *italic*, [text](https://...)."""
    out = []
    for para in re.split(r"\n\s*\n", md.strip()):
        t = _esc(para.strip()).replace("\n", " ")
        t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
        t = re.sub(r"\*(.+?)\*", r"<em>\1</em>", t)
        t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" rel="noopener noreferrer">\1</a>', t)
        out.append(f"<p>{t}</p>")
    return "".join(out)


def _editorial_html(ctx: Ctx, blocks: list[tuple[str, Optional[str]]], source_ids: list[str]) -> str:
    parts = [f'<h3>{_esc(title)}</h3><div class="editorial-text">{_markdown(text)}</div>' for title, text in blocks if text]
    if not parts:
        return ""
    links = ", ".join(x for x in (_source_link(ctx, s) for s in source_ids) if x)
    cite = f'<p class="fact-meta">Sources: {links}</p>' if links else ""
    return f'<section class="panel-section editorial">{"".join(parts)}{cite}</section>'


def resort_editorial(ctx: Ctx, r: dict) -> str:
    e = r.get("editorial")
    if not e or e.get("status") != "reviewed":
        return ""
    return _editorial_html(ctx, [("Overview", e.get("overview_md")), ("Culture", e.get("culture_md")),
                                 ("Alexandre's take", e.get("alexandre_take_md"))], e.get("source_ids") or [])


def cluster_editorial(ctx: Ctx, c: dict) -> str:
    """Reviewed cluster overview and Alexandre's take (clusters.geojson carries only reviewed text)."""
    return _editorial_html(ctx, [("Overview", c.get("overview_md")), ("Alexandre's take", c.get("alexandre_take_md"))],
                           c.get("sources") or [])


