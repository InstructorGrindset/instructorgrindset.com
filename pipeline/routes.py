"""Generate the static Career Map pages under /map/ and the map entries in /sitemap.xml.

GitHub Pages has no rewrites, so every deep link needs a real file. Each page is
a copy of /map/index.html with:

* its own <title>, meta description, canonical URL and Open Graph tags,
* JSON-LD (SkiResort with geo for resorts, CollectionPage with an ItemList for
  states and clusters, plus a BreadcrumbList),
* prerendered summary HTML from data/build between the `prerender` markers, so
  crawlers and visitors without JavaScript see the content. The map JavaScript
  replaces it with the interactive panel.
* on resort pages, the resort's full resorts.json record and the sources it cites, as
  `<script type="application/json" id="resort-record">`, so the panel can show the
  resort without waiting for the full resorts.json.

    /map/{state}/index.html
    /map/{state}/{cluster}/index.html
    /map/{state}/{cluster}/{resort}/index.html

A cluster that spans states gets a page under every one of its states; the
canonical URL uses the first state in cluster.states. A resort's canonical URL
uses the resort's own state when that state is one of the cluster's states.
Only canonical URLs go into the sitemap: /map/, every state and cluster page, and
Tier A resort pages. Tier B resort pages are generated and crawlable but left out of
the sitemap.

Generated pages are listed in /map/.routes-manifest.json and carry a marker
comment. Stale pages are removed on the next run. /map/index.html, /map/js,
/map/css, /map/vendor and the hand written /map/credits/ page are never touched;
the credits page joins the sitemap when it exists. In sitemap.xml only entries
under /map/ are rewritten; every other entry is kept as it is.

Keep the title and description wording in step with map/js/meta.js.

It also writes data/build/map-index.json, the slim national index the map loads
first (one compact row per resort, enough for the national, state and cluster
views, the list view and the map markers). The full resorts.json loads after the
first paint. See docs/map/ARCHITECTURE.md, "Frontend".

    python pipeline/routes.py            # uses this repository
    python pipeline/routes.py --root DIR # any directory with data/build and map/index.html
"""
