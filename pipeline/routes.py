# ── Text helpers (match map/js/ui.js and map/js/meta.js) ──

def _plural(n: int, one: str, many: str) -> str:
    return f"{n:,} {one if n == 1 else many}"


def _join_and(items: list[str]) -> str:
    if len(items) <= 1:
        return "".join(items)
    return f"{', '.join(items[:-1])} and {items[-1]}"


def _esc(text: Any) -> str:
    return html.escape(str(text), quote=True)


def _date(iso: Optional[str]) -> str:
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})", str(iso or ""))
    return f"{MONTHS[int(m.group(2)) - 1]} {int(m.group(3))}, {m.group(1)}" if m else str(iso or "")


def _month_day(mmdd: str) -> str:
    m = re.match(r"^(\d{2})-(\d{2})$", str(mmdd))
    return f"{MONTHS[int(m.group(1)) - 1]} {int(m.group(2))}" if m else str(mmdd)


def _num(v: float) -> str:
    return f"{v:,.0f}" if float(v).is_integer() else f"{v:,.1f}"


def _money(v: float, cents: bool = False) -> str:
    return f"${v:,.2f}" if cents and not float(v).is_integer() else f"${v:,.0f}"


