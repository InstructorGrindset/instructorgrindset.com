"""Phase 7 staleness job: list every sourced value older than staleness.max_age_months.

    python -m pipeline.staleness          # writes docs/map/staleness.md from data/build

Reads data/build/resorts.json and data/build/detail/*.json. A value is stale when
its as_of (or verified_date) plus max_age_months calendar months is before today
(see pipeline.career.is_stale). Every build also refreshes the report.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path
from typing import Any, Iterator, Optional

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    __package__ = "pipeline"

from pipeline.career import is_stale  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
SKIP_KEYS = {"editorial", "sources", "tier_a_criteria", "approval"}


def _date(v: Any) -> Optional[dt.date]:
    try:
        return dt.date.fromisoformat(str(v)[:10])
    except ValueError:
        return None


def dated_values(obj: Any, path: str = "") -> Iterator[tuple[str, dt.date, Optional[str]]]:
    """(field path, date, source_id) for every Sourced value (as_of) and every verified_date in ``obj``."""
    if isinstance(obj, dict):
        if "as_of" in obj and ("source_id" in obj or "value" in obj):
            d = _date(obj["as_of"])
            if d:
                yield path, d, obj.get("source_id")
        if "verified_date" in obj and isinstance(obj.get("verified_date"), str):
            d = _date(obj["verified_date"])
            if d:
                yield f"{path}.verified_date".lstrip("."), d, obj.get("location_source_id") or obj.get("source_id")
        for k, v in obj.items():
            if k in SKIP_KEYS or k in ("as_of", "verified_date"):
                continue
            yield from dated_values(v, f"{path}.{k}".lstrip("."))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            label = v.get("cert_level") or v.get("id") if isinstance(v, dict) else None
            yield from dated_values(v, f"{path}.{label if label else i}")


def stale_values(build_dir: Path, today: dt.date, max_age_months: int) -> dict[str, list[tuple[str, dt.date, Optional[str]]]]:
    """{resort_id: [(field, as_of, source_id)]} for stale values, sorted."""
    out: dict[str, list] = {}
    resorts_path = build_dir / "resorts.json"
    if resorts_path.exists():
        for r in json.loads(resorts_path.read_text(encoding="utf-8"))["resorts"]:
            for path, d, src in dated_values({k: v for k, v in r.items() if k not in SKIP_KEYS}):
                if is_stale(d, today, max_age_months):
                    out.setdefault(r["id"], []).append((path, d, src))
    for p in sorted((build_dir / "detail").glob("*.json")) if (build_dir / "detail").is_dir() else []:
        detail = json.loads(p.read_text(encoding="utf-8"))
        for key in ("housing", "rent_baseline", "rent_reported"):
            for path, d, src in dated_values(detail.get(key), key):
                if is_stale(d, today, max_age_months):
                    out.setdefault(detail["resort_id"], []).append((f"detail.{path}", d, src))
    return {k: sorted(v) for k, v in sorted(out.items())}


def render(stale: dict, today: dt.date, max_age_months: int) -> str:
    n = sum(len(v) for v in stale.values())
    lines = [
        "# Stale values",
        "",
        f"Sourced values verified more than {max_age_months} months before {today.isoformat()} "
        "(`staleness.max_age_months` in config/definitions.yaml). Generated by `python -m pipeline.staleness` "
        "and by every build. Re verify each value at its source, update `as_of` or `verified_date`, and rebuild.",
        "",
        f"{n} stale values at {len(stale)} resorts.",
        "",
    ]
    for rid, rows in stale.items():
        lines += [f"## `{rid}`", "", "| Field | As of | Source |", "|---|---|---|"]
        lines += [f"| {f} | {d.isoformat()} | {f'`{s}`' if s else ''} |" for f, d, s in rows]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_report(build_dir: Path, path: Path, max_age_months: int, today: dt.date) -> int:
    stale = stale_values(build_dir, today, max_age_months)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(stale, today, max_age_months), encoding="utf-8")
    return sum(len(v) for v in stale.values())


def main() -> int:
    from pipeline.build import build_date
    from pipeline.config import load_config

    months = load_config().definitions.staleness.max_age_months
    n = write_report(REPO_ROOT / "data" / "build", REPO_ROOT / "docs" / "map" / "staleness.md", months, build_date())
    print(f"{n} stale values listed in docs/map/staleness.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
