"""Write docs/map/tier-a-draft.md: the Tier A review table for Alexandre.

This is the approval document for the ROADMAP Section 3 gate. It is
regenerated by every build (``python pipeline/build.py``), or on its own:

    python pipeline/tier_a_report.py
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import TYPE_CHECKING

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    __package__ = "pipeline"

from pipeline.config import Config  # noqa: E402
from pipeline.sources import SourceRegistry  # noqa: E402

if TYPE_CHECKING:
    from pipeline.build import BuildResult
    from pipeline.schemas import Resort

CRITERION_LABEL = {
    "diehard": "Diehard following",
    "luxury": "Luxury",
    "athlete_development": "Athlete development",
    "heritage": "Heritage",
    "operator_compensation": "Operator compensation",
    "year_round_training": "Year round training",
    "owner_selection": "Owner selection",
}
FACILITY_LABEL = {"ski_area": "ski area", "indoor": "indoor", "training_center": "training center"}
# Fields reviewed for completeness, in display order.
CHECKED_FIELDS = [
    ("owner", lambda r: r.owner),
    ("acres", lambda r: r.size.acres),
    ("vertical_ft", lambda r: r.size.vertical_ft),
    ("lifts", lambda r: r.size.lifts),
    ("ski_school_staff_est", lambda r: r.size.ski_school_staff_est),
    ("base_ft", lambda r: r.elevation.base_ft),
    ("summit_ft", lambda r: r.elevation.summit_ft),
    ("open_typical", lambda r: r.season.open_typical),
    ("close_typical", lambda r: r.season.close_typical),
    ("length_days", lambda r: r.season.length_days),
    ("training_start", lambda r: r.season.training_start),
    # Phase 4 career layer
    ("pay", lambda r: (r.career.pay or None) if r.career else None),
    ("private_rate", lambda r: r.career.private_rate if r.career else None),
    ("private_split", lambda r: r.career.private_split if r.career else None),
    ("client_profile_tags", lambda r: r.clients.profile_tags or None),
]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _link(registry: SourceRegistry, source_id: str) -> str:
    if source_id in registry:
        s = registry.get(source_id)
        return f"[{_cell(s.title)}]({s.url})"
    return f"`{source_id}` (undefined)"


def _owned_by(entry, resort: "Resort") -> bool:
    from pipeline.names import name_similarity
    from pipeline.tier_a import OWNERSHIP_NAME_MIN

    if entry.resort_id:
        return entry.resort_id == resort.id
    return entry.state == resort.state and name_similarity(entry.name, resort.name) >= OWNERSHIP_NAME_MIN


def missing_fields(resort: "Resort") -> list[str]:
    return [name for name, get in CHECKED_FIELDS if get(resort) is None]


def render(result: "BuildResult", registry: SourceRegistry, cfg: Config) -> str:
    tier_a = [r for r in result.resorts if r.tier == "A"]
    cluster_names = {c.id: c.name for c in result.clusters}
    lines = [
        "# Tier A draft list",
        "",
        "Review document for the ROADMAP Section 3 gate. Generated by `python pipeline/build.py` "
        "from `data/raw/tier_a/` and `data/raw/ownership/`. Edit the research YAML, then rebuild. "
        "Hand edits to this file are overwritten.",
        "",
        "A resort qualifies when it meets at least one criterion: diehard following, luxury, athlete "
        "development, heritage, operator compensation (every Vail Resorts and Alterra US resort), or year "
        "round training (indoor slopes and training facilities). Each criterion below carries its source.",
        "",
        "**How to approve:** add `tier_a_status: approved` and `approval: {by, date, note}` to a record in "
        "`data/raw/tier_a/`, or set `status: approved` on a whole batch (each record then still needs its "
        "`approval` block). Approved rows are listed first.",
        "",
    ]
    batches = result.inputs.batches if result.inputs else []
    if not tier_a:
        lines += [
            "## Status",
            "",
            "No Tier A records have been researched yet. Research batches go in `data/raw/tier_a/` "
            "(format in `data/raw/tier_a/README.md`) and verified Vail and Alterra portfolios go in "
            "`data/raw/ownership/`. The list appears here after the next build.",
            "",
        ]
    else:
        approved = sum(1 for r in tier_a if r.tier_a_status == "approved")
        lines += [
            "## Summary",
            "",
            f"* {len(tier_a)} Tier A resorts in {len(batches)} research batches",
            f"* {approved} approved, {len(tier_a) - approved} draft",
            "",
            "## Batches",
            "",
            "| Batch | Researched | Status | Resorts |",
            "|---|---|---|---|",
        ]
        for b in sorted(batches, key=lambda b: b.batch.batch):
            lines.append(f"| {b.batch.batch} | {b.batch.researched_date} | {b.batch.status} | {len(b.batch.resorts)} |")
        lines += [
            "",
            "## Resorts",
            "",
            "| Resort | Facility | State | Owner | Cluster | Approval | Criteria | Missing fields |",
            "|---|---|---|---|---|---|---|---|",
        ]
        order = {"approved": 0, "draft": 1}
        for r in sorted(tier_a, key=lambda r: (order.get(r.tier_a_status, 2), r.state, r.name.lower())):
            owner = f"{_cell(r.owner.value)} ({_link(registry, r.owner.source_id)})" if r.owner else "unknown"
            crit = "<br>".join(
                f"**{CRITERION_LABEL[c.criterion]}**: {_cell(c.rationale)} ({_link(registry, c.source_id)})"
                for c in r.tier_a_criteria
            )
            missing = ", ".join(missing_fields(r)) or "none"
            cluster = f"{cluster_names.get(r.cluster_id, r.cluster_id)} (`{r.cluster_id}`)"
            if r.approval:
                approval = f"approved by {_cell(r.approval.by)} on {r.approval.date}"
                if r.approval.note:
                    approval += f": {_cell(r.approval.note)}"
            else:
                approval = "draft"
            lines.append(
                f"| {_cell(r.name)} (`{r.id}`) | {FACILITY_LABEL[r.facility_type]} | {r.state} | {owner} | {cluster} "
                f"| {approval} | {crit} | {missing} |"
            )
        lines.append("")

    ownership = result.inputs.ownership if result.inputs else []
    if ownership:
        lines += ["## Ownership portfolios", ""]
        for lo in sorted(ownership, key=lambda o: o.file.operator):
            f = lo.file
            cites = ", ".join(_link(registry, s.id) for s in f.sources)
            lines += [
                f"### {_cell(f.operator)}",
                "",
                f"Verified {f.verified_date}. Sources: {cites}.",
                "",
                "| Resort | State | Tier A record |",
                "|---|---|---|",
            ]
            for e in sorted(f.resorts, key=lambda e: (e.state, e.name.lower())):
                has = any(_owned_by(e, r) for r in tier_a)
                lines.append(f"| {_cell(e.name)} | {e.state} | {'yes' if has else '**missing**'} |")
            lines.append("")

    notes = [w for w in result.warnings if "has no Tier A record" in w or "OpenSkiMap" in w and "Tier A resort" in w]
    if notes:
        lines += ["## Open items", ""] + [f"* {_cell(w)}" for w in notes] + [""]
    return "\n".join(lines).rstrip() + "\n"


def write_report(path: Path, result: "BuildResult", registry: SourceRegistry, cfg: Config) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(result, registry, cfg), encoding="utf-8")
    return path


def main() -> int:
    from pipeline.build import REPO_ROOT, build
    from pipeline.tier_a import BuildError

    try:
        result = build(REPO_ROOT, write_report=True)
    except BuildError as e:
        print("cannot write the report: the build failed", file=sys.stderr)
        for m in e.errors:
            print(f"  - {m}", file=sys.stderr)
        return 1
    print(f"wrote {REPO_ROOT / 'docs/map/tier-a-draft.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
